// codegen.cpp
// Phase 1: deterministic AST -> C++ code generation.
//
// Determinism discipline (per the blueprint):
//   - We NEVER iterate an unordered_map/unordered_set when producing output.
//     The "declared variables" symbol table below is a plain std::vector
//     searched with std::find - slower than a hash set, but its contents
//     never affect output ORDER, only membership, and iteration order over
//     it is simply insertion order (fully deterministic).
//   - We never embed timestamps, build IDs, or any other non-reproducible
//     data into the generated source.
// This matters later: Phase 5's Diverse-Double-Compiling defense only works
// if "same input -> same output" holds exactly, every time.

#include "codegen.hpp"
#include <algorithm>
#include <stdexcept>

namespace {

std::string indentStr(int level) { return std::string(static_cast<size_t>(level) * 4, ' '); }

std::string escapeStringLiteral(const std::string& raw) {
    std::string out;
    out.reserve(raw.size() + 2);
    for (char c : raw) {
        if (c == '"' || c == '\\') out += '\\';
        out += c;
    }
    return out;
}

std::string genTerm(const TermNode& term) {
    switch (term.kind) {
        case TermNode::Kind::IDENT:
            return term.text;
        case TermNode::Kind::STRING:
            return "\"" + escapeStringLiteral(term.text) + "\"";
        case TermNode::Kind::NUMBER:
            return term.text;
    }
    throw std::runtime_error("codegen: unknown term kind");
}

std::string genExpression(const ExpressionNode& expr) {
    std::string code;
    for (size_t i = 0; i < expr.terms.size(); ++i) {
        if (i > 0) code += " == ";
        code += genTerm(*expr.terms[i]);
    }
    return code;
}

// Forward declaration: statements and function defs are mutually recursive
// (a FuncDefNode is itself a StmtNode, in case of nested definitions).
std::string genStmt(const StmtNode& stmt, int indent, std::vector<std::string>& declared);

std::string genFuncDef(const FuncDefNode& node, int indent) {
    std::string ind = indentStr(indent);
    std::string code = ind + "auto " + node.name + "(";
    for (size_t i = 0; i < node.params.size(); ++i) {
        if (i > 0) code += ", ";
        // Every TinyLang parameter is treated as a read-only string reference.
        // TinyLang has no type annotations, and the language's only two
        // literal kinds (STRING, NUMBER) are both usable as std::string-
        // comparable values for the "==" operator this grammar supports.
        code += "const std::string& " + node.params[i];
    }
    code += ") {\n";

    // Fresh symbol table for this function's own scope. Parameters count as
    // already-declared so reassigning a parameter doesn't emit a bogus
    // second "auto" declaration.
    std::vector<std::string> declared(node.params.begin(), node.params.end());
    for (const auto& s : node.body) {
        code += genStmt(*s, indent + 1, declared);
    }
    code += ind + "}\n";
    return code;
}

std::string genStmt(const StmtNode& stmt, int indent, std::vector<std::string>& declared) {
    std::string ind = indentStr(indent);

    if (const auto* a = dynamic_cast<const AssignStmtNode*>(&stmt)) {
        bool alreadyDeclared = std::find(declared.begin(), declared.end(), a->name) != declared.end();
        std::string code = ind + (alreadyDeclared ? "" : "auto ") + a->name +
                            " = " + genExpression(*a->value) + ";\n";
        if (!alreadyDeclared) declared.push_back(a->name);
        return code;
    }

    if (const auto* r = dynamic_cast<const ReturnStmtNode*>(&stmt)) {
        return ind + "return " + genExpression(*r->value) + ";\n";
    }

    if (const auto* iff = dynamic_cast<const IfStmtNode*>(&stmt)) {
        std::string code = ind + "if (" + genExpression(*iff->condition) + ") {\n";
        // A new block scope: seeded with a COPY of the enclosing scope's
        // declared vars (so it won't redeclare them), but anything newly
        // declared inside the if-block does not leak back out - this
        // mirrors real C++ block-scoping rules.
        std::vector<std::string> innerDeclared = declared;
        for (const auto& s : iff->body) {
            code += genStmt(*s, indent + 1, innerDeclared);
        }
        code += ind + "}\n";
        return code;
    }

    if (const auto* f = dynamic_cast<const FuncDefNode*>(&stmt)) {
        return genFuncDef(*f, indent);
    }

    throw std::runtime_error("codegen: encountered unknown statement node type");
}

} // namespace

std::string generateProgram(const ProgramNode& program) {
    std::string code;
    code += "// Auto-generated by the TinyLang compiler. Do not edit by hand.\n";
    code += "#include <string>\n";
    code += "#include <iostream>\n";
    code += "\n";

    std::vector<std::string> globalDeclared;
    for (const auto& stmt : program.statements) {
        code += genStmt(*stmt, 0, globalDeclared);
        code += "\n";
    }
    return code;
}
